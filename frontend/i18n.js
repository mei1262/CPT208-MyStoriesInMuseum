  function getLocale() {
    var v = localStorage.getItem(STORAGE_KEY);
    return v === 'en' ? 'en' : 'zh';
  }

  function t(key) {
    var loc = getLocale();
    var table = STR[loc] || STR.zh;
    if (table[key] != null) return table[key];
    return (STR.zh[key] != null ? STR.zh[key] : key);
  }

  function applyI18n(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!key) return;
      el.textContent = t(key);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(key));
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (key) el.innerHTML = t(key);
    });
    var pageTitleKey = document.documentElement.getAttribute('data-page-title-key') || 'meta.pageTitle';
    document.title = t(pageTitleKey);
    document.documentElement.lang = getLocale() === 'en' ? 'en' : 'zh-CN';
  }

  function syncLangToggle() {
    var loc = getLocale();
    document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
      var L = btn.getAttribute('data-lang-btn');
      var on = L === loc;
      btn.classList.toggle('bg-amber-500', on);
      btn.classList.toggle('text-white', on);
      btn.classList.toggle('border-amber-500', on);
      btn.classList.toggle('bg-white', !on);
      btn.classList.toggle('text-zinc-600', !on);
      btn.classList.toggle('border-zinc-200', !on);
    });
  }

  function setLocale(lang) {
    localStorage.setItem(STORAGE_KEY, lang === 'en' ? 'en' : 'zh');
    applyI18n();
    syncLangToggle();
    refreshVoiceSelectI18n();
    if (typeof window.vmRefreshPlanKeywords === 'function') window.vmRefreshPlanKeywords();
    if (typeof window.vmAfterLocaleChange === 'function') window.vmAfterLocaleChange();
    if (typeof window.vmSecondaryPageAfterLocale === 'function') {
      try { window.vmSecondaryPageAfterLocale(); } catch (e) {}
    }
  }

  function refreshVoiceSelectI18n() {
    var sel = document.getElementById('voice-select');
    if (!sel) return;
    var opts = sel.querySelectorAll('option');
    var keys = ['voice.opt1', 'voice.opt2', 'voice.opt3'];
    opts.forEach(function (op, i) {
      if (keys[i]) op.textContent = t(keys[i]);
    });
  }

  window.VMI18n = {
    getLocale: getLocale,
    setLocale: setLocale,
    t: t,
    applyI18n: applyI18n,
    syncLangToggle: syncLangToggle,
    refreshVoiceSelectI18n: refreshVoiceSelectI18n
  };

  function bootI18n() {
    applyI18n();
    syncLangToggle();
    refreshVoiceSelectI18n();
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', bootI18n);
  } else {
    bootI18n();
  }
